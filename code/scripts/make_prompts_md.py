"""Writes PROMPTS.md: every kind of prompt used in the experiments, word for word, each with one filled-in example,
and the definitions of the tools. Everything is produced by the same functions that the run scripts use.

Usage: python scripts/make_prompts_md.py        (rewrites PROMPTS.md in the package root)
"""
import _path  # noqa: F401
import json
import os

from particle_agents import ising, lanes, roles
from particle_agents.tools import OptionDraw, RandomUniform, RoleDraw, ROLE_DRAW_ERROR, OPTION_DRAW_ERROR

out = []


def w(*lines):
    out.extend(lines)


def block(text):
    w("```text", text, "```", "")


def tool(t, replies):
    w(f"- name: `{t.name}`", f"- description: \"{t.description}\"", "- parameters (JSON schema):", "", "```json",
      json.dumps(t.parameters(), indent=2), "```", "", f"- reply to the model: {replies}", "")


def iq(group, own, k, mode="shuffled"):
    return next(q for q in ising.queries(group) if q["own"] == own and q["k"] == k and q["mode"] == mode)


w("# Prompts", "",
  "Every prompt below is the complete user message of one query; nothing precedes it except, where one is set, "
  "the one-line system prompt `Answer the question.`. The examples are generated by `scripts/make_prompts_md.py`, with the default base seed, from the "
  "same functions that the run scripts use (`particle_agents/ising.py`, `roles.py`, `lanes.py`). "
  "What changes from query to query is stated for each prompt; the fixed sentences never change.", "")

# ------------------------------------------------------------------ Ising
w("## 1. Ising single particle", "",
  "### 1.1 Tests with letters", "",
  "The two states are shown as A and B. In the randomized queries the program draws for every query which letter denotes +1 "
  "and the order of the four neighbours; in the identical prompts both are fixed. Four versions differ only in the rule line.", "")
q = iq("rule", 1, 3)
w(f"**Scoring rule stated** (`rule`; example `{q['id']}`: own state +1, three neighbours +1, {q['labels'][0]} = +1)", "")
block(ising.prompt(q))
q = iq("norule", -1, 1)
w(f"**No rule sentence** (`norule`; example `{q['id']}`: own state -1, one neighbour +1, {q['labels'][0]} = +1)", "")
block(ising.prompt(q))
q = iq("switch_tie", 1, 2)
w(f"**Rule and \"if equal, switch\"** (`switch_tie`; example `{q['id']}`: tie, {q['labels'][0]} = +1). The added sentence follows the rule on the same line.", "")
block(ising.prompt(q))
q = iq("random_tie", -1, 2)
w(f"**Rule and \"if equal, choose one at random\"** (`random_tie`; example `{q['id']}`: tie, {q['labels'][0]} = +1)", "")
block(ising.prompt(q))
q = iq("random_tie", 1, 2, "identical")
w("**Identical prompts** of the same test: own state +1 or -1, letters AB or BA, neighbours fixed as +1, -1, +1, -1; each of the four "
  f"texts is sent repeatedly (example `{q['id']}`).", "")
block(ising.prompt(q))
w("### 1.2 Temperature tests", "",
  "Spins are shown as +1 and -1, neighbours in state +1 are listed first, and the queries of a cell are identical. "
  "The test with the tool uses the same prompt; the prompt does not mention the tool.", "")
q = next(q for q in ising.queries("temperature") if q["T"] == 2.27 and q["own"] == 1 and q["k"] == 3)
w(f"Example `{q['id']}`: T = 2.27, own spin +1, three neighbours +1.", "")
block(ising.prompt(q))
w("**Tool offered in the test `temperature_tool`**", "")
tool(RandomUniform(), "the number, rounded to four decimals, as text (e.g. `0.0895`)")

# ------------------------------------------------------------------ three roles
w("## 2. Three-role problem", "",
  "In every query the program assigns the letters A, B, C to the three roles (six assignments) and shuffles the order of the six "
  "teammates. The examples show the local optimum (teammates 3-2-1, own role on the 1) unless stated otherwise.", "")
q = roles.make_query("0", roles.LOCAL_OPTIMUM, 0)
w(f"### 2.1 Goal and die (condition `0`; example `{q['id']}`)", "")
block(roles.prompt(q))
w("**Tool offered with every goal-and-die prompt**", "")
tool(RoleDraw(), f"`Role drawn: X` with X the letter drawn, or `{ROLE_DRAW_ERROR}`")
w("### 2.2 Added sentences (conditions H, F, I, S and their combinations)", "",
  "The sentences are added to the goal-and-die prompt, always in this place and order:", "",
  f"- **H** (hint), appended to the line \"{roles.SEES}\": \"{roles.HINT.strip()}\"",
  f"- **S** (order of updates), a line of its own: \"{roles.TURNS}\"",
  f"- **F** (facts about the whole team), a line of its own: \"{roles.FACTS}\"",
  f"- **I** (instruction), a line of its own: \"{roles.INSTRUCTION}\"", "")
q = roles.make_query("HSFI", roles.LOCAL_OPTIMUM, 0)
w(f"Example with all four (condition `HSFI`; `{q['id']}`):", "")
block(roles.prompt(q))
q = roles.local_optimum_query("nodie", 0)
w(f"### 2.3 Without the die (variant `nodie`; example `{q['id']}`)", "",
  "The goal-and-die prompt without the sentence on the tool; no tool is offered.", "")
block(roles.prompt(q))
q = roles.local_optimum_query("explain", 0)
w(f"### 2.4 Reason first (variant `explain`; example `{q['id']}`)", "",
  "The goal-and-die prompt with its last sentence replaced; the die is offered as in 2.1.", "")
block(roles.prompt(q))
w("### 2.5 Prescribed rules", "",
  "No goal and no tool. The random number in the heat-bath prompts is drawn by the program for every query.", "")
for key, title in (("greedy", "Greedy rule (condition `greedy`)"), ("T0.4", "Heat bath with the random number in the prompt (conditions `T0.4`, `T0.7`)"),
                   ("Tc0.5", "Heat bath only at conflicts (condition `Tc0.5`)")):
    q = roles.make_query(key, roles.LOCAL_OPTIMUM, 0)
    w(f"**{title}**; example `{q['id']}`", "")
    block(roles.prompt(q))

# ------------------------------------------------------------------ lanes
w("## 3. Counterflow in three lanes", "",
  "In every query of the collective runs the program draws the names of the three lanes (six assignments of A, B, C) and the order "
  "in which the lanes are listed (six orders), 36 combinations. The cells of a lane are always listed from offset +2 to -2. "
  "The list of moves, the tool sentence and the last sentence name only the moves open to the bird (two for an outer lane, three for "
  "the middle lane).", "")
view = {(0, 2): "-"}
w("### 3.1 With the die", "", "Example: a bird in an outer lane meets one other bird one cell apart, nothing else in view; lanes named A, B, C in order.", "")
block(lanes.prompt(0, view, True))
t = lanes.tool_for(0)
w("**Tool offered with this prompt** (the options are the moves open to this bird, in the order of the prompt, then `Stay`)", "")
tool(t, f"`Option drawn: X`, or `{OPTION_DRAW_ERROR}`")
w("### 3.2 Without the die", "", "The same situation. The sentence beginning \"A tool named draw\" is absent, no tool is offered, and the prompt is otherwise identical.", "")
block(lanes.prompt(0, view, False))
birds = lanes.initial_state_random(1)
i = 4
nm = lanes.naming_for_query(1, 1, i)
w("### 3.3 A query of a collective run", "",
  f"Bird {i} in round 1 of a run with run seed 1 (random initial state), with the die. Lane names by lane 0, 1, 2: {', '.join(nm[0])}; "
  f"lanes listed in the order {', '.join(nm[0][y] for y in nm[1])}.", "")
block(lanes.prompt(birds[i][0][1], lanes.view_of(birds, i), True, nm))
w("### 3.4 Repeated queries", "",
  "A bird in an outer lane meets one other bird head-on, adjacent or one cell apart, nothing else in view, without the die. "
  "The text of 3.2 is the situation \"one cell apart\" with fixed lane names; \"adjacent\" has the other bird at offset +1. "
  "Each is asked repeatedly with fixed names and once with each of the 36 namings.", "")

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "PROMPTS.md")
with open(path, "w") as f:
    f.write("\n".join(out).rstrip() + "\n")
print("written:", os.path.normpath(path))
